insert into public.item_check_units (item_id, check_unit_id)
select i.id, cu.id
from public.items i
join public.cycles c on c.name = '月単位'
join public.check_units cu on cu.cycle_id = c.id and cu.location_id is null
where i.location_id is null
  and not exists (
    select 1 from public.item_check_units icu where icu.item_id = i.id
  );
